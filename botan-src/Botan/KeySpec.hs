-- As in, specificer or specification; spec for short
-- Very related to 'distribution'
class HasSpec a where
    type Spec a :: Type
    spec :: a -> Spec a

-- Static spec
class (HasSpec a) => StaticSpec a where
    staticSpec :: Spec a

class (HasSpec a) => HasStrat a where
    type Strat a :: Type
    validateStrat :: Spec a -> Strat a -> Bool

stratIsValid :: forall a . (HasStrat a) => Strat a -> Spec a -> Bool
stratIsValid = flip (validateStrat @a)

class (HasStrat a) => PreferredStrat a where
    preferredStrat :: Spec a -> Strat a

type StaticPreferred a = (StaticSpec a, PreferredStrat a)

-- INVARIANT: A value generated by a preferred strat is always valid for the static spec
staticPreferred :: forall a . (StaticPreferred a) => Strat a
staticPreferred = preferredStrat @a (staticSpec @a)

-- TODO: Generalize to require MonadRandom plus take a random generator
-- That way we can pass in the RNG while not limiting ourself to the stock RNG
-- NOTE: Being able to create a custom RNG might allow for easier interop too.
genStaticPreferred :: forall a m . (Monad m, StaticPreferred a) => (Spec a -> Strat a -> m (Maybe a)) -> m a
genStaticPreferred f = fromJust <$> f (staticSpec @a) (staticPreferred @a)

