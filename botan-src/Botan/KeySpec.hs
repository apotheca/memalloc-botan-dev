class ({- IsSecretKey (SecretKey a) , -} HasSpec (SecretKey a)) => HasSecretKey a where
    type SecretKey a :: Type
    getSecretKeySpec :: a -> Spec (SecretKey a)

-- NOTE: a m instead of m a to allow for easier @type applications
class (Monad m, HasSecretKey a, HasStrat (SecretKey a)) => GenSecretKey a m where
    genSecretKeyWith :: Spec (SecretKey a) -> Strat (SecretKey a) -> m (Maybe (SecretKey a))

-- NOTE: fromJust should be safe due to the invariant
genSecretKey :: forall a m . (GenSecretKey a m, StaticPreferred (SecretKey a)) => m (SecretKey a)
genSecretKey = genStaticPreferred @(SecretKey a) (genSecretKeyWith @a)

