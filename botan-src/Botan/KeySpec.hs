{-
Generic size specifier
-}

type role SizeSpec phantom
data SizeSpec a
    = SizeEnum Int Int Int -- NOTE: Is min max mod
    | SizeList [ Int ]     -- INVARIANT: Not empty, in increasing order
    | SizeExact Int
    deriving stock (Eq, Ord, Show)

sizeSpec :: Int -> Int -> Int -> SizeSpec a
sizeSpec mn mx _ | mn == mx = SizeExact mn
sizeSpec mn mx md           = SizeEnum mn mx md

minSize :: SizeSpec a -> Int
minSize (SizeEnum mn _ _) = mn
minSize (SizeList sizes) = minimum sizes
minSize (SizeExact size) = size

maxSize :: SizeSpec a -> Int
maxSize (SizeEnum _ mx _) = mx
maxSize (SizeList sizes) = maximum sizes
maxSize (SizeExact size) = size

allSizes :: SizeSpec a -> [Int]
allSizes (SizeEnum mn mx md) = [ mn, (mn + md) .. mx ]
allSizes (SizeList sizes) = sizes
allSizes (SizeExact size) = [ size ]

mapSizes :: (Int -> Int) -> SizeSpec a -> SizeSpec b
mapSizes f (SizeEnum mn mx md) = SizeEnum (f mn) (f mx) (f md)
mapSizes f (SizeList sizes)    = SizeList (fmap f sizes)
mapSizes f (SizeExact size)    = SizeExact (f size)

validSize :: SizeSpec a -> Int -> Bool
validSize (SizeEnum mn mx md) sz = mn <= sz && sz <= mx && mod sz md == 0
validSize (SizeList sizes) sz = sz `elem` sizes
validSize (SizeExact size) sz = sz == size

sizeIsValid :: Int -> SizeSpec a -> Bool
sizeIsValid sz sp = validSize sp sz

coerceSizeSpec :: forall a b . SizeSpec a -> SizeSpec b
coerceSizeSpec = mapSizes id

